const {test,expect}=require('@playwright/test')
const {offline}=require('../browser/helpers.cjs')
for(const colorScheme of ['light','dark']) {
    test(`native ${colorScheme} 404 recovery uses shared local foundations with JavaScript disabled`,async({browser})=>{
        const context=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844},colorScheme,reducedMotion:'reduce'})
        const page=await context.newPage()
        const scripts=[],fonts=[]
        page.on('request',request=>{if(request.resourceType()==='script') scripts.push(request.url());if(request.resourceType()==='font')fonts.push(request.url())})
        await offline(page)
        const response=await page.goto('http://127.0.0.1:8788/nested/unavailable-report.html')
        expect(response.status()).toBe(404)
        expect(response.headers()['cache-control']).toBe('no-store')
        expect(response.headers()['content-security-policy']).toContain("default-src 'none'")
        await expect(page.getByRole('heading',{name:'Not found'})).toBeVisible()
        await expect(page.locator('meta[http-equiv="Content-Security-Policy"]')).toHaveAttribute('content',/script-src 'none'/)
        expect(await page.locator('script').count()).toBe(0)
        await expect(page.locator('body')).toHaveCSS('background-color',colorScheme==='dark'?'rgb(10, 10, 11)':'rgb(255, 255, 255)')
        await expect(page.locator('body')).toHaveCSS('font-size','16px')
        await expect(page.getByRole('heading')).toHaveCSS('color',colorScheme==='dark'?'rgb(255, 153, 144)':'rgb(180, 35, 24)')
        await expect.poll(()=>fonts.length).toBeGreaterThan(0)
        expect(await page.evaluate(async()=>{await document.fonts.ready;return document.fonts.check('16px \"Geist Variable\"')})).toBe(true)
        expect(fonts.every(url=>url.startsWith('http://127.0.0.1:8788/assets/geist-') && url.endsWith('.woff2'))).toBe(true)
        const link=page.getByRole('link',{name:'Back to Home'})
        await page.keyboard.press('Tab')
        await expect(link).toBeFocused()
        await expect(link).toHaveCSS('outline-style','solid')
        await page.screenshot({path:`docs/evidence/pages-recovery-${colorScheme}-mobile.png`,fullPage:true})
        const headingBounds=await page.getByRole('heading').boundingBox()
        const identityBounds=await page.locator('.recovery-identity').boundingBox()
        expect(headingBounds.y).toBeGreaterThan(identityBounds.y+identityBounds.height)
        const bounds=await page.locator('main').boundingBox()
        expect(bounds.x).toBeGreaterThanOrEqual(0)
        expect(bounds.x+bounds.width).toBeLessThanOrEqual(390)
        expect(scripts).toEqual([])
        await page.keyboard.press('Enter')
        await page.waitForURL('http://127.0.0.1:8788/')
        await expect(page.locator('#ticker-input')).toBeVisible()
        await context.close()
    })
}
