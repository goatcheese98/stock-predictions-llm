async function observePolicy(page) {
    await page.addInitScript(()=>{
        window.pagesViolations=[]
        document.addEventListener('securitypolicyviolation',event=>window.pagesViolations.push({directive:event.effectiveDirective,blocked:event.blockedURI}))
    })
}
async function fonts(page,popup=false) {
    const result=await page.evaluate(async popup=>{
        const names=popup?['Geist Popup','Geist Mono Popup']:['Geist Variable','Geist Mono Variable']
        const loaded=await Promise.all(names.map(name=>document.fonts.load(`16px "${name}"`)))
        return loaded.map(faces=>faces.map(face=>face.status))
    },popup)
    expect(result.every(faces=>faces.length>0 && faces.every(status=>status==='loaded'))).toBe(true)
}
