test('real missing Pages chart chunk leaves source report intact and a restored file can render after reload',async({page})=>{
    const calls=await offline(page)
    await page.goto('/')
    const raw=JSON.stringify(stock)
    await page.evaluate(({raw,report})=>sessionStorage.setItem('stockReport',JSON.stringify({tickers:'AAPL',content:report.content,timestamp:1,dayRange:3,rawStockData:[raw]})),{raw,report})
    const asset=(await fs.readdir('dist/assets')).find(name=>name.startsWith('chart-runtime-'))
    const target=path.join('dist/assets',asset),original=await fs.readFile(target)
    await fs.unlink(target)
    try {
        const failure=page.waitForResponse(response=>response.url().endsWith('/'+asset))
        await page.goto('/report.html?id=fixture')
        const response=await failure
        expect(response.status()).toBe(404)
        expect(response.headers()['cache-control']).toBe('no-store')
        await expect(page.getByRole('status')).toContainText('Chart rendering is unavailable')
        await expect(page.locator('.report-content').first()).toHaveText(report.content)
        await expect(page.locator('#addDay-0')).toBeDisabled()
        expect(await page.evaluate(()=>JSON.parse(sessionStorage.getItem('stockReport')).rawStockData)).toEqual([raw])
    } finally {await fs.writeFile(target,original)}
    await page.reload()
    await page.waitForFunction(()=>window.stockCharts?.length===1)
    await expect(page.locator('#addDay-0')).toBeEnabled()
    expect(calls).toEqual([])
})
test('the retained Vue compiler and GSAP execute under the declared CSP; removing eval breaks compilation, not a stub',async({page})=>{
    await offline(page)
    await observePolicy(page)
    const intercept=async route=>{
        const response=await route.fetch()
        await route.fulfill({response,headers:{...response.headers(),'content-security-policy':response.headers()['content-security-policy'].replace(" 'unsafe-eval'",'')}})
    }
    await page.context().route('http://127.0.0.1:8788/',intercept)
    const error=page.waitForEvent('pageerror',{predicate:error=>error.message.includes('unsafe-eval')})
    await page.goto('/')
    await error
    expect(await page.evaluate(()=>window.vueApp)).toBeUndefined()
    await page.context().unroute('http://127.0.0.1:8788/',intercept)
    await page.reload()
    await page.waitForFunction(()=>window.vueApp?.confettiSystem.wiggle)
    expect(await page.evaluate(()=>{
        const timeline=window.vueApp.createExplosion(100,100,100)
        timeline.progress(.25)
        const result={count:document.querySelectorAll('.confetti-piece').length,transformed:[...document.querySelectorAll('.confetti-piece')].every(piece=>piece.style.transform.includes('translate'))}
        timeline.progress(1)
        return result
    })).toEqual({count:5,transformed:true})
    expect(await page.evaluate(()=>window.pagesViolations)).toEqual([])
})
